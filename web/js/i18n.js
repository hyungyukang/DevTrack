// 화면 틀의 한국어 / 영어 전환.
// 메뉴 · 머리말 · 탭 · 필터 · 버튼 · 상태 라벨 · 빈 화면 안내 · 날짜 형식만 바꾼다.
// 작업 내용(지시, 진행 기록, 결과물, 리뷰 리포트), 사용 방법 문서, AI 에게 보내는 메시지는 번역하지 않는다.
//
// 코드에는 한국어 문구를 그대로 쓰고 L('한국어') 로 감싼다. 영어 화면에서는 아래 EN 표에서 찾고,
// 표에 없으면 한국어를 그대로 보여 준다. {이름} 자리에는 L(문구, { 이름: 값 }) 의 값이 들어간다.
// 같은 한국어가 자리에 따라 다른 영어가 되면 '§' 뒤에 쓰임새를 붙인다: L('취소§상태') → 한국어 화면은 '취소',
// 영어 화면은 'Cancelled' (버튼의 L('취소') 는 'Cancel').

const KEY = 'devtrack.lang';
// 처음 열면(언어를 고른 적이 없으면) 영어 화면. 사용자가 고른 언어는 브라우저에 기억한다
let lang = 'en';
try {
  if (JSON.parse(localStorage.getItem(KEY)) === 'ko') lang = 'ko';
} catch { /* 저장소 사용 불가 */ }

export const getLang = () => lang;
/** Intl 날짜 · 시간 형식에 쓰는 로캘 */
export const locale = () => (lang === 'en' ? 'en' : 'ko');

export function setLang(next) {
  lang = next === 'ko' ? 'ko' : 'en';
  try { localStorage.setItem(KEY, JSON.stringify(lang)); } catch { /* 저장소 사용 불가 */ }
  document.documentElement.lang = lang;
}

const has = (k) => Object.prototype.hasOwnProperty.call(EN, k);

/** 화면 문구. 영어 화면이면 번역, 아니면 그대로. {이름} 자리 채우기 */
export function L(ko, vars) {
  let s = lang === 'en' && has(ko) ? EN[ko] : ko.split('§')[0];
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return s;
}

/** 라벨 표(STATUS 등)의 label · hint 를 읽을 때마다 현재 언어로. 원래 한국어는 labelKo 로 남긴다 */
export function translated(map) {
  for (const v of Object.values(map)) {
    for (const f of ['label', 'hint']) {
      if (typeof v[f] !== 'string') continue;
      const ko = v[f];
      if (f === 'label') v.labelKo = ko.split('§')[0];
      Object.defineProperty(v, f, { get: () => L(ko), enumerable: true, configurable: true });
    }
  }
  return map;
}

/** { 키: '한국어' } 표의 값을 읽을 때마다 현재 언어로 */
export function translatedStrings(obj) {
  for (const k of Object.keys(obj)) {
    const ko = obj[k];
    Object.defineProperty(obj, k, { get: () => L(ko), enumerable: true, configurable: true });
  }
  return obj;
}

/** index.html 의 고정 틀: data-i18n(글자) · data-i18n-title · data-i18n-aria 에 적힌 한국어 문구를 현재 언어로 */
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = L(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = L(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', L(el.dataset.i18nAria)); });
}

